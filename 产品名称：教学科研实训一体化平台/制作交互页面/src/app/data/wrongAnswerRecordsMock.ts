export function wrongRecordMonthStats(rows: WrongAnswerRecord[]): {
  monthCount: number;
  pendingFollowUps: number;
  totalCount: number;
} {
  const totalCount = rows.length;
  const monthCount = rows.filter((r) => MONTH_HINT.test(r.occurredAt)).length;
  const pendingFollowUps = rows.filter((r) => r.recordStatus === "pending_redo").length;
  return { monthCount, pendingFollowUps, totalCount };
}